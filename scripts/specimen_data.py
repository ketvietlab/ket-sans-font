"""Export real outline data from the built OTF for the specimen.

    .venv/bin/python scripts/specimen_data.py   (also run by build.py)

Writes specimen/data.js: metrics, the design system, the supported codepoints
and every glyph's cubic outline with on/off-curve points.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from fontTools.pens.recordingPen import DecomposingRecordingPen  # noqa: E402
from fontTools.pens.svgPathPen import SVGPathPen  # noqa: E402
from fontTools.ttLib import TTFont  # noqa: E402

from ketsans.system import ROOT, SYSTEM_PATH, load  # noqa: E402


def main() -> None:
    system = load("Regular")
    otf = ROOT / "fonts" / "otf" / f"{system.meta.postscriptFamily}-Regular.otf"
    font = TTFont(otf)
    gs = font.getGlyphSet()
    cmap = font.getBestCmap()
    by_name = {}
    for cp, name in cmap.items():
        by_name.setdefault(name, []).append(cp)
    import ufoLib2

    ufo = ufoLib2.Font.open(ROOT / "sources" / f"{system.meta.postscriptFamily}-Regular.ufo")
    notes = {g.name: g.lib.get("vn.ketviet.construction", "") for g in ufo}
    production = {v: k for k, v in ufo.lib.get("public.postscriptNames", {}).items()}
    glyphs = {}
    for name in font.getGlyphOrder():
        if name in (".notdef",):
            continue
        rec = DecomposingRecordingPen(gs)
        gs[name].draw(rec)
        svg = SVGPathPen(gs)
        gs[name].draw(svg)
        points = []
        for op, args in rec.value:
            if op in ("moveTo", "lineTo"):
                points.append([round(args[0][0]), round(args[0][1]), 1])
            elif op == "curveTo":
                for i, p in enumerate(args):
                    points.append([round(p[0]), round(p[1]), 1 if i == 2 else 0])
        glyphs[name] = {
            "u": by_name.get(name, []),
            "w": font["hmtx"][name][0],
            "d": svg.getCommands(),
            "p": points,
        }
        note = notes.get(production.get(name, name), "")
        if note:
            glyphs[name]["note"] = note
    data = {
        "version": system.meta.version,
        "phase": system.meta.phase,
        "metrics": system.raw["metrics"],
        "system": json.loads(SYSTEM_PATH.read_text(encoding="utf-8")),
        "codepoints": sorted(cmap),
        "glyphs": glyphs,
    }
    out = ROOT / "specimen" / "data.js"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("// Generated by scripts/specimen_data.py from the built OTF. Do not edit.\nwindow.KET_SANS = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)} ({len(glyphs)} glyphs, {out.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()
